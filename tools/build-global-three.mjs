import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, '..', 'web', 'vendor', 'three.module.min.js');
const out = path.join(here, '..', 'web', 'vendor', 'three.global.min.js');

const text = fs.readFileSync(src, 'utf8');
const idx = text.lastIndexOf('export{');
if (idx < 0) throw new Error('no export statement found');

let body = text.slice(0, idx);
const exportBody = text.slice(idx + 'export{'.length, text.lastIndexOf('}'));
const pairs = exportBody.split(',').map((entry) => {
  const m = entry.trim().match(/^(.+?)\s+as\s+(\w+)$/);
  return m ? `${m[2]}:${m[1]}` : `${entry.trim()}:${entry.trim()}`;
});

// Module top-level bindings become IIFE-scoped so classic-script globals stay untouched.
const globalBuild =
  `/* three.js r160 (MIT) 鈥?classic-script build generated by tools/build-global-three.mjs */\n` +
  `(function(){"use strict";\n${body}\n` +
  `globalThis.THREE=Object.freeze({${pairs.join(',')}});\n})();\n`;

fs.writeFileSync(out, globalBuild);
console.log('wrote', out, globalBuild.length, 'bytes,', pairs.length, 'exports');

